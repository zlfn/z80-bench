#!/usr/bin/env python3
"""Write input.c: 4 KB of word salad, raw deflate compressed by zlib."""

import zlib
from pathlib import Path

WORDS = ("the of and to in is that for it as was with be by on not he this are "
         "or his from at which but have an they you were her she there been one "
         "all we their has would when if so no will more can out other into "
         "benchmark compiler register stack frame carry zero sign parity "
         "accumulator memory cycle byte word sixteen eight bit").split()
SIZE = 4096


def text() -> bytes:
    out = bytearray()
    x = 12345
    while len(out) < SIZE:
        # A fixed LCG, so the text never depends on Python's random module.
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        out += WORDS[(x >> 16) % len(WORDS)].encode()
        out += b".\n" if (x & 0xF) == 0 else b" "
    return bytes(out[:SIZE])


def main():
    c = zlib.compressobj(9, zlib.DEFLATED, -15)
    data = c.compress(text()) + c.flush()
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n\t".join(rows)
    Path(__file__).with_name("input.c").write_text(
        "/* Generated by gen-input.py. */\n\n"
        "#include <stdint.h>\n\n"
        f"const uint16_t bench_input_len = {len(data)};\n"
        f"const uint16_t bench_output_len = {SIZE};\n\n"
        f"const uint8_t bench_input[{len(data)}] = {{\n\t{body}\n}};\n")


if __name__ == "__main__":
    main()
