#!/usr/bin/env python3
"""Write input.c: the 4 KB of text that puff inflates, compressed with ZX0.

The compressor is ZX0 v2.2's zx0, given as the first argument or found on the
PATH."""

import importlib.util
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def text() -> bytes:
    spec = importlib.util.spec_from_file_location("puff_input", HERE.parent / "puff" / "gen-input.py")
    puff = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(puff)
    return puff.text()


def main():
    zx0 = sys.argv[1] if len(sys.argv) > 1 else "zx0"
    raw = text()
    with tempfile.TemporaryDirectory() as d:
        src, dst = Path(d) / "text", Path(d) / "text.zx0"
        src.write_bytes(raw)
        subprocess.run([zx0, src, dst], check=True, stdout=subprocess.DEVNULL)
        data = dst.read_bytes()
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n\t".join(rows)
    (HERE / "input.c").write_text(
        "/* Generated by gen-input.py. */\n\n"
        "#include <stdint.h>\n\n"
        f"const uint16_t bench_input_len = {len(data)};\n"
        f"const uint16_t bench_output_len = {len(raw)};\n\n"
        f"const uint8_t bench_input[{len(data)}] = {{\n\t{body}\n}};\n")


if __name__ == "__main__":
    main()
