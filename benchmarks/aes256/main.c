/* AES-256 in CBC mode over 4 KB with tiny-AES-c, key expansion included.
 * Key and IV are the CBC-AES256 example from NIST SP 800-38A, F.2.5. */

#include "bench.h"
#include "aes.h"

#define LEN 4096

static uint8_t buf[LEN];

static const uint8_t key[32] = {
	0x60, 0x3d, 0xeb, 0x10, 0x15, 0xca, 0x71, 0xbe, 0x2b, 0x73, 0xae, 0xf0, 0x85, 0x7d, 0x77, 0x81,
	0x1f, 0x35, 0x2c, 0x07, 0x3b, 0x61, 0x08, 0xd7, 0x2d, 0x98, 0x10, 0xa3, 0x09, 0x14, 0xdf, 0xf4,
};

static const uint8_t iv[16] = {
	0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
};

static struct AES_ctx ctx;

int main(void)
{
	bench_fill(buf, LEN);
	bench_begin();
	AES_init_ctx_iv(&ctx, key, iv);
	AES_CBC_encrypt_buffer(&ctx, buf, LEN);
	bench_end();
	bench_result = bench_hash(buf, LEN);
	bench_done();
	return 0;
}
